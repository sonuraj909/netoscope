import 'package:dio/dio.dart';
import 'package:retrofit/retrofit.dart';

part 'user_api.g.dart';

/// A user returned by the API.
class User {
  /// Creates a user.
  const User({required this.id, required this.name, required this.token});

  /// Parses a user.
  factory User.fromJson(Map<String, dynamic> json) => User(
    id: json['id'] as int,
    name: json['name'] as String,
    token: json['token'] as String,
  );

  /// The user ID.
  final int id;

  /// The display name.
  final String name;

  /// A session token.
  final String token;

  /// Serializes the user.
  Map<String, dynamic> toJson() => {'id': id, 'name': name, 'token': token};
}

/// A typical Retrofit API. The implementation is generated by
/// `retrofit_generator` and runs on the Dio instance passed in.
@RestApi()
abstract class UserApi {
  /// Creates the API on [dio].
  factory UserApi(Dio dio, {String? baseUrl}) = _UserApi;

  /// Fetches a user.
  @GET('/users/{id}')
  Future<User> getUser(@Path('id') int id, {@Query('api_key') String? apiKey});

  /// Logs in.
  @POST('/login')
  Future<void> login(@Body() Map<String, dynamic> body);
}
